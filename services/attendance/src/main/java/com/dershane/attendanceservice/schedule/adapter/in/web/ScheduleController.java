package com.dershane.attendanceservice.schedule.adapter.in.web;

import com.dershane.attendanceservice.schedule.adapter.in.web.dto.CreateScheduleRequest;
import com.dershane.attendanceservice.schedule.adapter.in.web.dto.ScheduleResponse;
import com.dershane.attendanceservice.schedule.adapter.in.web.dto.UpdateScheduleRequest;
import com.dershane.attendanceservice.schedule.application.port.in.CreateScheduleUseCase;
import com.dershane.attendanceservice.schedule.application.port.in.DeactivateScheduleUseCase;
import com.dershane.attendanceservice.schedule.application.port.in.GetScheduleQuery;
import com.dershane.attendanceservice.schedule.application.port.in.ListSchedulesQuery;
import com.dershane.attendanceservice.schedule.application.port.in.UpdateScheduleUseCase;
import com.dershane.attendanceservice.shared.adapter.in.security.SecurityRoles;
import com.dershane.attendanceservice.shared.adapter.in.web.CurrentActor;
import com.dershane.attendanceservice.shared.adapter.in.web.idempotency.Idempotent;
import com.dershane.attendanceservice.shared.application.Actor;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import java.net.URI;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Pageable;
import org.springframework.data.web.PagedModel;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

@Tag(name = "Class schedules")
@RestController
@RequestMapping("/api/v1/class-schedules")
@RequiredArgsConstructor
@PreAuthorize(SecurityRoles.ANY_ADMIN)
class ScheduleController {

  private final CreateScheduleUseCase createSchedule;
  private final UpdateScheduleUseCase updateSchedule;
  private final DeactivateScheduleUseCase deactivateSchedule;
  private final GetScheduleQuery getSchedule;
  private final ListSchedulesQuery listSchedules;
  private final ScheduleWebMapper mapper;

  @Operation(summary = "Create a weekly schedule; its sessions are generated by a daily job")
  @PostMapping
  @Idempotent
  public ResponseEntity<ScheduleResponse> create(
      @CurrentActor Actor actor, @Valid @RequestBody CreateScheduleRequest request) {
    ScheduleResponse created =
        mapper.toResponse(createSchedule.create(actor, mapper.toCommand(request)));
    return ResponseEntity.created(URI.create("/api/v1/class-schedules/" + created.id()))
        .body(created);
  }

  @Operation(summary = "List schedules (branch defaults to the caller's branch)")
  @GetMapping
  public PagedModel<ScheduleResponse> list(
      @CurrentActor Actor actor,
      @RequestParam(required = false) UUID branchId,
      @RequestParam(required = false) UUID classroomId,
      @RequestParam(required = false) UUID teacherId,
      @RequestParam(required = false) Boolean active,
      Pageable pageable) {
    return new PagedModel<>(
        listSchedules
            .list(actor, branchId, classroomId, teacherId, active, pageable)
            .map(mapper::toResponse));
  }

  @Operation(summary = "Get a schedule")
  @GetMapping("/{scheduleId}")
  public ScheduleResponse get(@CurrentActor Actor actor, @PathVariable UUID scheduleId) {
    return mapper.toResponse(getSchedule.get(actor, scheduleId));
  }

  @Operation(summary = "Replace the changeable fields; applies to sessions generated from now on")
  @PutMapping("/{scheduleId}")
  public ScheduleResponse update(
      @CurrentActor Actor actor,
      @PathVariable UUID scheduleId,
      @Valid @RequestBody UpdateScheduleRequest request) {
    return mapper.toResponse(updateSchedule.update(actor, scheduleId, mapper.toCommand(request)));
  }

  @Operation(summary = "Deactivate a schedule (deleting means deactivating; sessions stay)")
  @DeleteMapping("/{scheduleId}")
  public ScheduleResponse deactivate(@CurrentActor Actor actor, @PathVariable UUID scheduleId) {
    return mapper.toResponse(deactivateSchedule.deactivate(actor, scheduleId));
  }
}
