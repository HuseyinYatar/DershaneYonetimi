"""Builds a TYT answer key and a matching optical reader file for trying the API by hand.

Subject and topic ids are generated by seed-catalog, so they are read from the running API:

    TOKEN=... python3 local/demo/make_demo_files.py [output_dir]

Writes answer-key.json (body of PUT /mock-exams/{id}/answer-key) and tyt-optik.txt
(file for POST /mock-exams/{id}/import-jobs, format tyt-fwf-v1).
"""

import json
import os
import random
import sys
import urllib.request
from pathlib import Path

API = os.environ.get("API", "http://localhost:8000/api/v1")
# Question ranges of the tyt-fwf-v1 answer segments: 40 + 20 + 40 + 20.
SECTIONS = [("TUR", 40), ("SOS", 20), ("MAT", 40), ("FEN", 20)]
OPTIONS = "ABCDE"


def get(path: str) -> list[dict]:
    request = urllib.request.Request(API + path, headers={"Authorization": f"Bearer {os.environ['TOKEN']}"})
    with urllib.request.urlopen(request) as response:
        return json.load(response)


def leaf_topics(subject_id: str) -> list[dict]:
    topics = get(f"/subjects/{subject_id}/topics")
    parents = {topic["parentTopicId"] for topic in topics}
    return [topic for topic in topics if topic["id"] not in parents]


def build_key(rng: random.Random) -> list[dict]:
    exam_type = next(t for t in get("/exam-types") if t["code"] == "TYT")
    subjects = {s["code"]: s for s in get(f"/exam-types/{exam_type['id']}/subjects")}
    items = []
    question_no = 0
    for code, count in SECTIONS:
        topics = leaf_topics(subjects[code]["id"])
        for i in range(count):
            question_no += 1
            topic = topics[i % len(topics)]
            for booklet in "AB":
                items.append(
                    {
                        "booklet": booklet,
                        "questionNo": question_no,
                        "subjectId": subjects[code]["id"],
                        "topicId": topic["id"],
                        "correctAnswer": rng.choice(OPTIONS),
                    }
                )
    return items


def answer_sheet(rng: random.Random, correct: list[str], skill: float, blank_rate: float) -> str:
    answers = []
    for right in correct:
        roll = rng.random()
        if roll < blank_rate:
            answers.append(" ")
        elif roll < blank_rate + (1 - blank_rate) * skill:
            answers.append(right)
        else:
            answers.append(rng.choice([option for option in OPTIONS if option != right]))
    return "".join(answers)


def line(student_no: str, booklet: str, answers: str) -> str:
    return f"{student_no:<10}{booklet}{answers}"


def main() -> None:
    out = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).parent / "out")
    out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(1234)
    items = build_key(rng)
    correct = {
        booklet: [item["correctAnswer"] for item in items if item["booklet"] == booklet] for booklet in "AB"
    }

    lines = [
        line("ST7001", "A", answer_sheet(rng, correct["A"], skill=0.85, blank_rate=0.05)),  # Ali
        line("ST7002", "B", answer_sheet(rng, correct["B"], skill=0.65, blank_rate=0.10)),  # Ayşe
        # Can wrote his number wrong (ST7030 instead of ST7003): STUDENT_NOT_FOUND, match it by hand.
        line("ST7030", "A", answer_sheet(rng, correct["A"], skill=0.45, blank_rate=0.20)),
        # Torn sheet: only the number survived. MALFORMED_LINE, ignore it by hand.
        "ST7050",
    ]

    (out / "answer-key.json").write_text(json.dumps({"items": items}, ensure_ascii=False, indent=1))
    (out / "tyt-optik.txt").write_text("\n".join(lines) + "\n", encoding="windows-1254")
    print(f"{len(items)} key items, {len(lines)} lines -> {out}")


if __name__ == "__main__":
    main()
